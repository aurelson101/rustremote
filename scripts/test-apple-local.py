#!/usr/bin/env python3
"""Apple ARD type-30 simulation. Private X11 and loopback only; not a real Mac.
The test's plain loopback RFB transport is NOT the production connection policy,
which requires SSH. No personal display, credentials or system account is used.
"""
import ctypes as c
import hashlib
import json
import os
from pathlib import Path
import secrets
import select
import socket
import struct
import subprocess
import tempfile
import threading
import time
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.primitives.asymmetric import dh
from PIL import ImageGrab

os.umask(0o077)
children=[]
streams=[]
stop=threading.Event()

def run(args,**kwargs):return subprocess.run(args,check=True,capture_output=True,timeout=15,**kwargs)
def start(args,path,env,**kwargs):
    stream=open(path,'wb');streams.append(stream)
    p=subprocess.Popen(args,env=env,stdout=stream,stderr=stream,start_new_session=True,**kwargs)
    children.append(p);return p

def wait(fn,message,seconds=15):
    end=time.monotonic()+seconds
    while time.monotonic()<end:
        if fn():return
        time.sleep(.1)
    raise AssertionError(message)

def read(sock,size):
    data=b''
    while len(data)<size:
        part=sock.recv(size-len(data))
        if not part:raise EOFError()
        data+=part
    return data

def listener():
    s=socket.socket();s.bind(('127.0.0.1',0));s.listen(1);s.settimeout(15);return s

def type_credentials(env,username,password):
    # Inputs go exclusively to the password dialog in this private Xvfb.
    def dialog():
        tree=run(['xwininfo','-root','-tree'],env=env).stdout.decode()
        for line in tree.splitlines():
            if 'Authentication' in line or 'authentication' in line:
                return int(line.strip().split()[0],16)
    wait(dialog,'Private TigerVNC authentication dialog absent')
    x=c.CDLL('libX11.so.6');xt=c.CDLL('libXtst.so.6')
    x.XOpenDisplay.argtypes=[c.c_char_p];x.XOpenDisplay.restype=c.c_void_p
    x.XStringToKeysym.argtypes=[c.c_char_p];x.XStringToKeysym.restype=c.c_ulong
    x.XKeysymToKeycode.argtypes=[c.c_void_p,c.c_ulong];x.XKeysymToKeycode.restype=c.c_uint
    x.XSetInputFocus.argtypes=[c.c_void_p,c.c_ulong,c.c_int,c.c_ulong]
    x.XFlush.argtypes=[c.c_void_p];x.XCloseDisplay.argtypes=[c.c_void_p]
    xt.XTestFakeKeyEvent.argtypes=[c.c_void_p,c.c_uint,c.c_int,c.c_ulong]
    display=x.XOpenDisplay(env['DISPLAY'].encode());assert display
    def key(name,ctrl=False):
        code=x.XKeysymToKeycode(display,x.XStringToKeysym(name.encode()));assert code
        control=x.XKeysymToKeycode(display,x.XStringToKeysym(b'Control_L'))
        if ctrl:xt.XTestFakeKeyEvent(display,control,1,0)
        xt.XTestFakeKeyEvent(display,code,1,0);xt.XTestFakeKeyEvent(display,code,0,0)
        if ctrl:xt.XTestFakeKeyEvent(display,control,0,0)
        x.XFlush(display)
    try:
        x.XSetInputFocus(display,dialog(),1,0);x.XFlush(display);time.sleep(.2)
        key('a',True)
        for letter in username:key(letter)
        key('Tab');key('a',True)
        for letter in password:key(letter)
        key('Return')
    finally:x.XCloseDisplay(display)

summary={'target':'127.0.0.1','real_mac_tested':False,'personal_desktop_accessed':False,'cases':{}}
try:
    with tempfile.TemporaryDirectory(prefix='rustremote-apple-') as folder:
        base=Path(folder);env=dict(os.environ,HOME=str(base),XDG_CONFIG_HOME=str(base/'config'))
        def display(binary,label,extra):
            auth=base/(label+'.auth');auth.touch(mode=0o600)
            cookie=secrets.token_hex(16)
            run(['xauth','-f',str(auth)],input=f'add :65534 . {cookie}\n'.encode())
            r,w=os.pipe()
            start([binary,'-displayfd',str(w),'-auth',str(auth),'-nolisten','tcp','-noreset',*extra],base/(label+'.log'),env,pass_fds=(w,))
            os.close(w);assert select.select([r],[],[],10)[0]
            number=int(os.read(r,32));os.close(r)
            assert ':'+str(number)!=os.environ.get('DISPLAY')
            run(['xauth','-f',str(auth)],input=f'add :{number} . {cookie}\n'.encode())
            return dict(env,DISPLAY=':'+str(number),XAUTHORITY=str(auth))
        probe=listener();backend_port=probe.getsockname()[1];probe.close()
        desktop=display('Xtigervnc','desktop',['-geometry','800x600','-rfbport',str(backend_port),'-localhost','yes','-SecurityTypes','None'])
        client_env=display('Xvfb','client',['-screen','0','1280x900x24'])
        os.environ['XAUTHORITY']=client_env['XAUTHORITY']
        run(['xsetroot','-solid','#315d81'],env=desktop)
        start(['xmessage','-geometry','500x140+40+40','Apple ARD simulation - not macOS\nEphemeral macOS account / type 30'],base/'message.log',desktop)
        # Public DH parameters generated by the crypto library, never copied keys.
        prime=dh.generate_parameters(generator=2,key_size=1024).parameter_numbers().p
        width=(prime.bit_length()+7)//8
        account='maclab';password=secrets.token_hex(12)
        for case in ('success','wrong-password','downgrade','invalid-key'):
            server=listener();port=server.getsockname()[1];events={};errors=[]
            def serve():
                try:
                    with server.accept()[0] as peer:
                        peer.settimeout(20);peer.sendall(b'RFB 003.889\n')
                        assert read(peer,12)==b'RFB 003.008\n'
                        peer.sendall(b'\x02\x01\x02' if case=='downgrade' else b'\x01\x1e')
                        if case=='downgrade':
                            try:assert peer.recv(1)==b''
                            except ConnectionResetError:pass
                            events['downgrade_rejected']=True;return
                        assert read(peer,1)==b'\x1e';events['type30_selected']=True
                        if case=='invalid-key':
                            peer.sendall(struct.pack('!HH',2,1025));assert peer.recv(1)==b''
                            events['invalid_key_rejected']=True;return
                        exponent=secrets.randbits(256)+2
                        peer.sendall(struct.pack('!HH',2,width)+prime.to_bytes(width,'big')+pow(2,exponent,prime).to_bytes(width,'big'))
                        encrypted=read(peer,128);public=int.from_bytes(read(peer,width),'big')
                        assert 1<public<prime-1
                        shared=pow(public,exponent,prime).to_bytes(width,'big')
                        key=hashlib.md5(shared,usedforsecurity=False).digest()
                        decoder=Cipher(algorithms.AES(key),modes.ECB()).decryptor()
                        credentials=decoder.update(encrypted)+decoder.finalize()
                        accepted=credentials[:64].split(b'\0')[0]==account.encode() and credentials[64:].split(b'\0')[0]==password.encode()
                        assert accepted==(case=='success')
                        del credentials,shared,key
                        peer.sendall(struct.pack('!I',0 if accepted else 1))
                        if not accepted:
                            text=b'Authentication rejected by local simulator';peer.sendall(struct.pack('!I',len(text))+text)
                            events['wrong_password_rejected']=True;return
                        events['account_authenticated']=True
                        with socket.create_connection(('127.0.0.1',backend_port),timeout=5) as backend:
                            read(backend,12);backend.sendall(b'RFB 003.008\n')
                            offered=read(backend,read(backend,1)[0]);assert 1 in offered
                            backend.sendall(b'\x01');assert read(backend,4)==bytes(4)
                            while not stop.is_set():
                                ready,_,_=select.select([peer,backend],[],[],.2)
                                for source in ready:
                                    data=source.recv(65536)
                                    if not data:return
                                    (backend if source is peer else peer).sendall(data)
                except Exception as error:
                    if not stop.is_set():errors.append(type(error).__name__)
                finally:server.close()
            thread=threading.Thread(target=serve,daemon=True);thread.start()
            viewer=start(['xtigervncviewer','-SecurityTypes','DH','-AcceptClipboard=0','-SendClipboard=0','-AlertOnFatalError=0','-ReconnectOnError=0',f'127.0.0.1::{port}'],base/(case+'.log'),client_env)
            if case in ('success','wrong-password'):
                type_credentials(client_env,account,password if case=='success' else secrets.token_hex(12))
            if case=='success':
                wait(lambda:events.get('account_authenticated'),'Apple account was not authenticated')
                time.sleep(1)
                frame=ImageGrab.grab(xdisplay=client_env['DISPLAY'])
                assert sum(abs(r-49)<8 and abs(g-93)<8 and abs(b-129)<8 for r,g,b in frame.convert('RGB').getdata())>1000,'Remote framebuffer missing'
                Path('dist').mkdir(exist_ok=True);frame.save('dist/apple-simulation.png')
                viewer.terminate();viewer.wait(timeout=5);thread.join(timeout=3)
                assert not thread.is_alive()
            else:
                viewer.wait(timeout=20);thread.join(timeout=3)
                assert not errors,(case,errors)
                expected={'wrong-password':'wrong_password_rejected','downgrade':'downgrade_rejected','invalid-key':'invalid_key_rejected'}[case]
                assert events.get(expected) and not events.get('account_authenticated'),case
            summary['cases'][case]=events
        summary['success']=True
finally:
    stop.set()
    for process in reversed(children):
        if process.poll() is None:
            process.terminate()
            try:process.wait(timeout=5)
            except subprocess.TimeoutExpired:process.kill();process.wait(timeout=5)
    for stream in streams:stream.close()
    summary['services_stopped']=all(p.poll() is not None for p in children)
    print(json.dumps(summary))
